import 'package:drift/drift.dart';

import 'package:echonotes/core/database/tables/action_items_table.dart';
import 'package:echonotes/core/database/tables/key_points_table.dart';
import 'package:echonotes/core/database/tables/note_tags_table.dart';
import 'package:echonotes/core/database/tables/notes_table.dart';
import 'package:echonotes/core/database/tables/transcript_segments_table.dart';

part 'app_database.g.dart';

/// The app's SQLite database: every note and its parts.
///
/// Changing a table? Follow "Changing the database schema" in CLAUDE.md, so
/// an app update never loses anyone's notes.
@DriftDatabase(
  tables: [Notes, KeyPoints, ActionItems, TranscriptSegments, NoteTags],
)
class AppDatabase extends _$AppDatabase {
  AppDatabase(super.executor);

  @override
  int get schemaVersion => 1;

  @override
  MigrationStrategy get migration => MigrationStrategy(
    onCreate: (migrator) => migrator.createAll(),
    onUpgrade: (migrator, from, to) async {
      if (from > to) {
        // An older build opened a database from a newer one. Stop instead of
        // guessing. Drift then leaves the database exactly as it was.
        throw StateError(
          'The database is at version $from, but this build only knows up '
          'to version $to.',
        );
      }
      // From version 2 on, the steps generated by make-migrations run here:
      // await stepByStep(from1To2: ...)(migrator, from, to);
    },
    beforeOpen: (details) async {
      // SQLite ignores foreign keys unless asked, and deleting a note relies
      // on them to delete its parts too.
      await customStatement('PRAGMA foreign_keys = ON');
    },
  );
}
